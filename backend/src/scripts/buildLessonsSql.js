// Turns content/lessons.js into sql/05_seed_lessons.sql
// Run:  npm run lessons:build   (then  npm run db:init  to load it)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { COURSES } from '../../content/lessons.js';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '../..');
const TYPES = new Set(['heading', 'text', 'code', 'output', 'tip']);
const q = (s) => "'" + String(s).replace(/'/g, "''") + "'";

let sql = '-- GENERATED by `npm run lessons:build` from content/lessons.js. Edit that file, not this one.\nBEGIN;\n';
let total = 0;

for (const c of COURSES) {
  const slugs = new Set();
  c.lessons.forEach((l, i) => {
    const where = `${c.course} / ${l.slug ?? '(no slug)'}`;
    if (!/^[a-z0-9-]+$/.test(l.slug ?? '')) throw new Error(`${where}: slug must use a-z, 0-9 and "-"`);
    if (slugs.has(l.slug)) throw new Error(`${where}: duplicate slug`);
    slugs.add(l.slug);
    if (!l.title) throw new Error(`${where}: missing title`);
    if (!Array.isArray(l.blocks) || !l.blocks.length) throw new Error(`${where}: no blocks`);
    for (const b of l.blocks) {
      if (!TYPES.has(b.type)) throw new Error(`${where}: unknown block type "${b.type}"`);
      if (b.type === 'code' ? !b.code : !b.text) throw new Error(`${where}: empty ${b.type} block`);
    }
    sql += `INSERT INTO lessons (course_code, position, slug, title, summary, content) VALUES (${q(c.course)}, ${i + 1}, ${q(l.slug)}, ${q(l.title)}, ${q(l.summary ?? '')}, ${q(JSON.stringify(l.blocks))}::jsonb)\n` +
      '  ON CONFLICT (course_code, slug) DO UPDATE SET position = EXCLUDED.position, title = EXCLUDED.title, summary = EXCLUDED.summary, content = EXCLUDED.content;\n';
    total++;
  });
}
sql += 'COMMIT;\n';
fs.writeFileSync(path.join(root, 'sql/05_seed_lessons.sql'), sql);
console.log(`wrote sql/05_seed_lessons.sql (${total} lessons in ${COURSES.length} courses)`);